-- 219：语音反射延迟（2026-10-27）
--
-- 为什么
--   指标里 `reflex_p50/p95` 一直写死 null，报告里只能写「缺观测点（voice_events
--   没有耗时列）」。而语音是家居场景的主入口 ——「说一句 → 灯亮」的延迟才是主人
--   真正感受到的速度，比模型 p50 更该看。没有这一列，这条链路一个数都拿不到。
--
-- 为什么由设备上报，而不是服务端掐表
--   服务端只看到"请求到达"，看不到"主人什么时候说完"和"灯什么时候真的亮"。
--   真正有意义的区间是【唤醒词结束 → 动作执行完】，只有设备端知道。服务端掐表
--   会把网络抖动算成设备慢，读数没有意义。
--
-- 为什么允许 NULL
--   不是所有事件都是一次反射：离线告警、状态上报没有"响应"这个动作。
--   这些行 latency_ms 留 NULL，指标只对非 NULL 的行算分位数 ——
--   绝不把 0 当成"极快"混进去。
--
-- 为什么有上限
--   超过 60 秒的"反射"已经不是反射了（多半是设备挂起后补报）。
--   让它进分位数会把 p95 拉到毫无意义的量级，所以超限按无观测处理。

ALTER TABLE voice_events ADD COLUMN latency_ms INTEGER;
CREATE INDEX idx_voice_events_latency ON voice_events(dot_id, at DESC) WHERE latency_ms IS NOT NULL;
