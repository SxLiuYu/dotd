-- 221：区分「按钮上线前的单子」（2026-10-27）
--
-- 为什么
--   220 加了 approvals_rememberable，用来判断"该记没记"。但一核账就发现：
--   本窗口 8 张可记忆档的单子**全是 10-22 发的**，而卡片上「以后都这样」
--   这个按钮是 10-27 才加上的。那批单子主人想点也点不到。
--
--   把它们算进"该记没记"，等于拿新规矩判旧账 —— 会催着人去修一个刚修好的东西。
--   所以按按钮上线时刻拆成两段：之前的单独计数，之后才计入"该记没记"。
--
-- 只加列，旧行 0；历史采样不受影响。

ALTER TABLE metric_sample ADD COLUMN approvals_rememberable_before INTEGER NOT NULL DEFAULT 0;
